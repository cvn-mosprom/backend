"""Generation pipeline checks: committed artefacts are reproducible and well-formed."""

from __future__ import annotations

import shutil
import subprocess

import pytest
from conftest import CONTRACT_DIR, GENERATED_DIR, SCHEMA_DIR

HEADER = "# GENERATED by contract/generate — do not edit."


@pytest.mark.parametrize("name", ["__init__.py", "command.py", "snapshot.py"])
def test_generated_files_have_header_and_lf(name):
    raw = (GENERATED_DIR / name).read_bytes()
    assert raw.startswith(HEADER.encode("utf-8"))
    assert b"\r\n" not in raw


@pytest.mark.parametrize("name", ["command.schema.json", "snapshot.schema.json"])
def test_schema_files_are_lf_and_sorted(name):
    import json

    raw = (SCHEMA_DIR / name).read_bytes()
    assert b"\r\n" not in raw and raw.endswith(b"\n")
    data = json.loads(raw)
    assert json.dumps(data, indent=2, sort_keys=True, ensure_ascii=False) + "\n" == raw.decode("utf-8")


def test_command_schema_is_discriminated_union_of_28(command_schema):
    cmd = command_schema["definitions"]["Command"]
    assert cmd["discriminator"]["propertyName"] == "type"
    assert len(cmd["oneOf"]) == 28 == len(cmd["discriminator"]["mapping"])


@pytest.mark.skipif(shutil.which("sh") is None, reason="POSIX sh not available")
def test_check_sh_reports_in_sync():
    """check.sh regenerates into a temp dir and diffs: exit 0 means the committed contract is current."""
    proc = subprocess.run(
        ["sh", str(CONTRACT_DIR / "check.sh")], capture_output=True, text=True, timeout=300, check=False
    )
    assert proc.returncode == 0, proc.stdout + proc.stderr
    assert "in sync" in proc.stdout
