"""Server-side quiz bank: questions about the company Ochakovo (facts of the museum, vendor/frontend content/facts.ts).

The correct option index lives ONLY here: `public()` never includes it, it is revealed per question after the answer
(answers are final, one attempt per question). Options are positions, answers are option indexes (0-based).
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Question:
    id: str
    text: str
    options: tuple[str, ...]
    correct: int
    explanation: str  # the museum fact; shown after the answer

    def public(self) -> dict[str, object]:
        return {"id": self.id, "text": self.text, "options": list(self.options)}


