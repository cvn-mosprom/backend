#!/usr/bin/env node
// GENERATED-CONTRACT PIPELINE (see contract/README.md)
//
//   vendor/frontend/web/src/lib/api/types.ts
//     -> ts-json-schema-generator -> contract/schema/{command,snapshot}.schema.json
//     -> datamodel-code-generator -> api/app/contract/generated/{command,snapshot}.py (+ __init__.py)
//
// Usage: node generate.mjs [--schema-dir DIR] [--py-dir DIR] [--schema-only]
// Defaults: schema -> contract/schema, python -> api/app/contract/generated.
// Output is deterministic: sorted keys, 2-space indent, LF line endings, no timestamps.

import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createGenerator } from 'ts-json-schema-generator';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');
const TYPES_TS = path.join(ROOT, 'vendor/frontend/web/src/lib/api/types.ts');
const TSCONFIG = path.join(HERE, 'tsconfig.json');

const HEADER = [
	'# GENERATED by contract/generate — do not edit.',
	'# Source: vendor/frontend/web/src/lib/api/types.ts (ts-json-schema-generator -> datamodel-code-generator).',
	'# Regenerate with: contract/generate.sh   |   Drift check: contract/check.sh'
].join('\n');

// ---------------------------------------------------------------- args
const args = process.argv.slice(2);
function opt(name, dflt) {
	const i = args.indexOf(name);
	return i >= 0 ? path.resolve(args[i + 1]) : dflt;
}
const schemaDir = opt('--schema-dir', path.join(HERE, 'schema'));
const pyDir = opt('--py-dir', path.join(ROOT, 'api/app/contract/generated'));
const schemaOnly = args.includes('--schema-only');

// ---------------------------------------------------------------- helpers
function sortKeys(v) {
	if (Array.isArray(v)) return v.map(sortKeys);
	if (v && typeof v === 'object') {
		return Object.fromEntries(Object.keys(v).sort().map((k) => [k, sortKeys(v[k])]));
	}
	return v;
}
const stable = (v) => JSON.stringify(sortKeys(v), null, 2) + '\n';
const pascal = (s) => s.charAt(0).toUpperCase() + s.slice(1);
const writeLF = (file, text) => {
	fs.mkdirSync(path.dirname(file), { recursive: true });
	fs.writeFileSync(file, text.replace(/\r\n/g, '\n'), { encoding: 'utf8' });
};

function genSchema(type) {
	return createGenerator({
		path: TYPES_TS,
		tsconfig: TSCONFIG,
		type,
		expose: 'export',
		topRef: true,
		jsDoc: 'none', // structure only: comment edits in the frontend must not cause drift
		skipTypeCheck: true, // `three` etc. are not installed here; we only need the data types
		additionalProperties: false, // strict objects: unknown fields are rejected
		sortProps: true,
		encodeRefs: false
	}).createSchema(type);
}

/**
 * Turn `Name = {k:'a',...} | {k:'b',...}` (anonymous members) into named definitions
 * `<A><suffix>` + `oneOf` of $refs, and add an OpenAPI-style `discriminator` so that
 * datamodel-code-generator emits a pydantic discriminated union.
 */
function nameVariants(schema, defName, key, suffix, { discriminator = true } = {}) {
	const def = schema.definitions[defName];
	if (!def || !Array.isArray(def.anyOf)) throw new Error(`${defName}: expected an anyOf union`);
	const refs = [];
	const mapping = {};
	for (const member of def.anyOf) {
		const c = member.properties?.[key]?.const;
		if (c === undefined) throw new Error(`${defName}: member without const "${key}"`);
		const name = typeof c === 'string' ? pascal(c) + suffix : defName + (c ? 'Ok' : 'Failed');
		if (schema.definitions[name]) throw new Error(`${defName}: duplicate variant definition ${name}`);
		schema.definitions[name] = member;
		refs.push({ $ref: `#/definitions/${name}` });
		mapping[String(c)] = `#/definitions/${name}`;
	}
	schema.definitions[defName] = discriminator
		? { discriminator: { mapping, propertyName: key }, oneOf: refs }
		: { anyOf: refs };
	return Object.keys(mapping);
}

function buildSchemas() {
	const command = genSchema('Command');
	const variants = nameVariants(command, 'Command', 'type', 'Command');
	nameVariants(command, 'SimEvent', 'k', 'SimEvent');

	const snapshot = genSchema('GameSnapshot');
	const result = genSchema('CommandResult');
	for (const [name, def] of Object.entries(result.definitions)) {
		if (name in snapshot.definitions && JSON.stringify(sortKeys(snapshot.definitions[name])) !== JSON.stringify(sortKeys(def))) {
			throw new Error(`definition ${name} differs between GameSnapshot and CommandResult runs`);
		}
		snapshot.definitions[name] = def;
	}
	nameVariants(snapshot, 'CommandResult', 'ok', '', { discriminator: false });
	return { command, snapshot, variants };
}

// ---------------------------------------------------------------- python
function findPython() {
	if (process.env.PYTHON) return process.env.PYTHON;
	for (const p of [path.join(HERE, '.venv/Scripts/python.exe'), path.join(HERE, '.venv/bin/python')]) {
		if (fs.existsSync(p)) return p;
	}
	throw new Error('contract/.venv not found. Run contract/generate.sh (it creates the venv) or set PYTHON=...');
}

/**
 * Run datamodel-code-generator on a *derived* copy of the committed schema whose root is the
 * definition `rootDef` (so the root class gets a clean name via --class-name and no stray
 * `Model` stub appears). The committed schema itself keeps the standard `$ref` root.
 */
function genPython(python, schemaFile, rootDef, outFile) {
	const schema = JSON.parse(fs.readFileSync(schemaFile, 'utf8'));
	const root = schema.definitions[rootDef];
	if (!root) throw new Error(`${schemaFile}: no definition ${rootDef}`);
	const definitions = { ...schema.definitions };
	delete definitions[rootDef];
	const derived = { $schema: schema.$schema, ...root, definitions };

	const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'mosprom-contract-'));
	const derivedFile = path.join(tmp, `${path.basename(schemaFile, '.schema.json')}.json`);
	const hdr = path.join(tmp, 'header.txt');
	fs.writeFileSync(derivedFile, stable(derived), 'utf8');
	fs.writeFileSync(hdr, HEADER + '\n', 'utf8');
	const r = spawnSync(
		python,
		[
			'-m', 'datamodel_code_generator',
			'--input', derivedFile,
			'--input-file-type', 'jsonschema',
			'--output', outFile,
			'--class-name', rootDef,
			'--output-model-type', 'pydantic_v2.BaseModel',
			'--target-python-version', '3.12',
			'--use-standard-collections',
			'--use-union-operator',
			'--use-annotated',
			'--enum-field-as-literal', 'all',
			'--collapse-root-models', // plain Literal[...] fields instead of RootModel enum wrappers
			'--reuse-model',
			'--disable-timestamp',
			'--custom-file-header-path', hdr,
			'--encoding', 'utf-8'
		],
		{ encoding: 'utf8', env: { ...process.env, PYTHONUTF8: '1', PYTHONIOENCODING: 'utf-8' } }
	);
	fs.rmSync(tmp, { recursive: true, force: true });
	if (r.status !== 0) {
		process.stderr.write((r.stdout ?? '') + (r.stderr ?? ''));
		throw new Error(`datamodel-code-generator failed for ${schemaFile}`);
	}
	writeLF(outFile, fs.readFileSync(outFile, 'utf8'));
}

function initPy(variants) {
	return `${HEADER}
"""Pydantic models generated from the frontend TypeScript contract.

\`Command\` is a discriminated union on \`type\`; \`GameSnapshot\` / \`CommandResult\` mirror the
snapshot types. Never edit by hand: run \`contract/generate.sh\`.
"""

from typing import Any

from .command import Command
from .snapshot import CommandResult, GameSnapshot

# Frozen list of command discriminator values, in declaration order of types.ts (includes \`tick\`).
COMMAND_TYPES: tuple[str, ...] = (
${variants.map((v) => `    "${v}",`).join('\n')}
)


def parse_command(data: Any):
    """Validate a raw command dict and return the concrete variant (e.g. \`PlaceCommand\`).

    Raises \`pydantic.ValidationError\` on unknown \`type\`, missing/extra fields.
    """
    return Command.model_validate(data).root


__all__ = ["COMMAND_TYPES", "Command", "CommandResult", "GameSnapshot", "parse_command"]
`;
}

// ---------------------------------------------------------------- main
const { command, snapshot, variants } = buildSchemas();
writeLF(path.join(schemaDir, 'command.schema.json'), stable(command));
writeLF(path.join(schemaDir, 'snapshot.schema.json'), stable(snapshot));
console.log(`schema: ${variants.length} command variants -> ${schemaDir}`);

if (!schemaOnly) {
	const python = findPython();
	fs.mkdirSync(pyDir, { recursive: true });
	genPython(python, path.join(schemaDir, 'command.schema.json'), 'Command', path.join(pyDir, 'command.py'));
	// GameSnapshot stays a definition (CommandResult references it); CommandResult becomes the root class.
	genPython(python, path.join(schemaDir, 'snapshot.schema.json'), 'CommandResult', path.join(pyDir, 'snapshot.py'));
	writeLF(path.join(pyDir, '__init__.py'), initPy(variants));
	console.log(`python: command.py, snapshot.py, __init__.py -> ${pyDir}`);
}
