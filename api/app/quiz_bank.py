"""Server-side quiz bank: the frontend's own bank (vendor/frontend/web/src/lib/api/mock/quiz.ts), one for the product.

The questions live in app/data/quiz_bank.json, generated by `python scripts/gen_quiz_bank.py` (the api image is built
from ./api, so it cannot read vendor/); api/tests/test_quiz_bank_drift.py fails when the file and the vendored TS differ.
The client sends the option id ('a' | 'b' | 'c'); an option index (0-based) is accepted too. The right answers are in
the client bundle anyway, so `public()` is not a secret store; the server decides what counts.
"""
from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

BANK_FILE = Path(__file__).resolve().parent / "data" / "quiz_bank.json"


@dataclass(frozen=True)
class Question:
    id: str
    fact_id: str  # museum fact the question stands on (content/facts.ts)
    text: str
    option_ids: tuple[str, ...]  # 'a', 'b', 'c': what the client sends
    options: tuple[str, ...]  # texts, same order
    correct: int  # index into options

    @property
    def correct_id(self) -> str:
        return self.option_ids[self.correct]

    def public(self) -> dict[str, object]:
        return {"id": self.id, "text": self.text, "options": list(self.options), "optionIds": list(self.option_ids)}

    def index_of(self, answer: object) -> int | None:
        """Option index for an answer given as the option id ('b') or as the 0-based index (1); None when invalid."""
        if isinstance(answer, bool):
            return None
        if isinstance(answer, int):
            return answer if 0 <= answer < len(self.options) else None
        if isinstance(answer, str):
            a = answer.strip().lower()
            return self.option_ids.index(a) if a in self.option_ids else None
        return None


def load(path: Path = BANK_FILE) -> tuple[Question, ...]:
    out = []
    for raw in json.loads(path.read_text(encoding="utf-8")):
        opts = raw["options"]
        ids = tuple(o["id"] for o in opts)
        out.append(Question(id=raw["id"], fact_id=raw["factId"], text=raw["text"], option_ids=ids,
                            options=tuple(o["text"] for o in opts), correct=ids.index(raw["correct"])))
    return tuple(out)


QUESTIONS: tuple[Question, ...] = load()
BY_ID: dict[str, Question] = {q.id: q for q in QUESTIONS}
assert QUESTIONS and len(BY_ID) == len(QUESTIONS)  # ids are unique
IDS: tuple[str, ...] = tuple(q.id for q in QUESTIONS)
TOTAL = len(QUESTIONS)
HIGH_SCORE = 0.75  # share of correct answers (of the whole bank) that earns the `high_quiz` lead tag: 6 of 8
